export function getLanguage(lang: UiLanguage | string): UiLanguage {
  if (lang === 'zh-CN' || lang === 'zh-TW' || lang === 'ja' || lang === 'ko' || lang === 'fr' || lang === 'en') {
    return lang;
  }
  const navigatorLang = navigator.language || 'en';
  if (navigatorLang.startsWith('zh')) return navigatorLang.startsWith('zh-TW') ? 'zh-TW' : 'zh-CN';
  if (navigatorLang.startsWith('ja')) return 'ja';
  if (navigatorLang.startsWith('ko')) return 'ko';
  if (navigatorLang.startsWith('fr')) return 'fr';
  return 'en';
}
